// Build timing.js from the real voice: node make_timing.mjs
import fs from 'fs';
const dur = JSON.parse(fs.readFileSync('voice/dur.json', 'utf8'));
const lines = JSON.parse(fs.readFileSync('voice/lines.json', 'utf8'));
const CHAP = { b1: 1, c1: 2, d1: 3, e1: 4, f1: 5, g1: 6 };
const TITLE = {
  b1: 'VỞ KỊCH ĐƯỢC VIẾT TRƯỚC KHI CÓ DIỄN VIÊN',
  c1: 'CUỐN SỔ CỦA ĐẠO DIỄN',
  d1: 'YÊU QUÁI NÀO CŨNG CÓ NGƯỜI QUEN',
  e1: 'KINH SÁCH LÀ MỘT MÓN HÀNG',
  f1: 'THỨ DUY NHẤT KHÔNG CÓ TRONG KỊCH BẢN',
  g1: 'KHÁN GIẢ',
};
const HOLD = { a5: 2.2, a7: 4.2, b11: 1.2, c12: 1.4, d16: 1.4, e19: 2.2, f13: 1.6, g14: 1.2, g18: 3.6, c4: 2.6, c8: 1.2, d4: 3.4, d13: 1.2, e9: 1.2, e15: 1.2, f6: 3.0, f8: 1.2, g4: 1.6, g8: 1.0 };
const GAP = 0.63, CHGAP = 0.7, MINT = 1.8, PAD = .6;   // a subtitle is held ≥ 1.8 s and ≥ speech + 0.6 s

let t = 2.6, L = {}, subs = [], ch = [], turns = [];
const list = [];
for (const ln of lines) {
  const d = dur[ln.id];
  if (!d) throw new Error('missing dur for ' + ln.id);
  if (CHAP[ln.id]) {
    t += 4.2;                       // the page turn sits in this gap
    turns.push([t - 2.7, t - 0.3]);
    ch.push({ id: ln.id, t0: t, spread: CHAP[ln.id], title: TITLE[ln.id] });
  } else t += GAP;
  // the next line may not start before this subtitle has been read: hold the line long enough
  const need = Math.max(d + PAD, MINT);
  const hold = Math.max(HOLD[ln.id] || 0, need + .06 - d - GAP);
  L[ln.id] = { t0: +t.toFixed(3), t1: +(t + d).toFixed(3), text: ln.text };
  subs.push({ t0: +(t - .05).toFixed(3), t1: +(t + need).toFixed(3), text: ln.text });
  t += d + hold;
  list.push(ln.id);
}
const CLOSE = [+(t + 1.4).toFixed(3), +(t + 3.6).toFixed(3)];
const DUR = +(CLOSE[1] + 4.6).toFixed(3);
const RISE = [5.9], FOLD = [];
for (let i = 0; i < turns.length; i++) { RISE.push(+(turns[i][1] + .7).toFixed(3)); FOLD.push(+(turns[i][0]).toFixed(3)); }
FOLD.push(1e9);
const OPEN = [3.0, 5.4];
const INSERTS = [
  { t0: L.c4.t0 - .4, t1: L.c5.t0 - .2, tag: 'HỒI 99', text: 'CÒN THIẾU MỘT NẠN', sub: 'Quán Thế Âm, cuốn nạn bạ' },
  { t0: L.d4.t0 + .2, t1: L.d5.t0 - .1, tag: 'HỒI 35', text: 'QUÁN ÂM MƯỢN HAI ĐỨA TRẺ BA LẦN', sub: 'Lão Tử nói với Ngộ Không', x: 1140, y: 150, w: 700 },
  { t0: L.e5.t0 + .2, t1: L.e6.t0 - .1, tag: 'HỒI 98', text: 'KINH KHÔNG THỂ TRUYỀN KHÔNG CÔNG', sub: 'Phật Tổ', x: 1140, y: 150, w: 700 },
  { t0: L.e11.t0 - .3, t1: L.e12.t1 + .3, tag: 'MỘT TẠNG', text: '5.048 CUỘN = 5.048 NGÀY', sub: 'đúng một con số' },
  { t0: L.f6.t0 + .4, t1: L.f7.t0 - .1, tag: 'HỒI 99', text: 'THIÊN ĐỊA BẤT TOÀN', sub: 'nên kinh cũng bất toàn', x: 1140, y: 150, w: 620 },
  { t0: L.g3.t0 + .1, t1: L.g4.t0 - .1, tag: 'HỒI 98', text: 'ĐÓ LÀ ÔNG', sub: 'cả bốn người cùng nói' },
];
const STAMPS = [L.c5.t0 + .35, L.d11.t0 + .3, L.e10.t0 + .3, L.g5.t0 + .3];
const POPSFX = [
  { t: L.f4.t0 + .1, type: 'splash' }, { t: L.f5.t0 + .4, type: 'tear' },
  { t: L.g3.t0, type: 'water' }, { t: L.b6.t0, type: 'flip' }, { t: L.d4.t0 + .3, type: 'ting' },
];
const out = `// generated by make_timing.mjs — do not edit by hand
export const DUR = ${DUR};
export const OPEN = ${JSON.stringify(OPEN)};
export const CLOSE = ${JSON.stringify(CLOSE)};
export const TURNS = ${JSON.stringify(turns.map(x => x.map(v => +v.toFixed(3))))};
export const RISE = ${JSON.stringify(RISE)};
export const FOLD = ${JSON.stringify(FOLD)};
export const L = ${JSON.stringify(L, null, 0)};
export const SUBS = ${JSON.stringify(subs)};
export const CH = ${JSON.stringify(ch)};
export const INSERTS = ${JSON.stringify(INSERTS)};
export const STAMPS = ${JSON.stringify(STAMPS.map(v => +v.toFixed(3)))};
export const POPSFX = ${JSON.stringify(POPSFX)};
`;
fs.writeFileSync('timing.js', out);
fs.writeFileSync('timing.json', JSON.stringify({ DUR, OPEN, CLOSE, TURNS: turns, RISE, FOLD, L, SUBS: subs, CH: ch, INSERTS, STAMPS, POPSFX }, null, 1));
console.log('speech', (Object.values(dur).reduce((a, b) => a + b, 0)).toFixed(1), 's  film', DUR, 's  turns', turns.length, 'chapters', ch.length);
console.log('last line ends', t.toFixed(1));
