// Identity and freshness audit of a film folder: node core/render/filmcheck.mjs <film-folder> [<film-folder> ...]
//
// A new episode of a series is usually started by copying the previous episode's folder. That copy carries the old
// episode with it: its treatment, its research file, its shots, its title, its file name in build.sh. Three rules:
//
//   1. build.sh must give the film a name that no other film of the library uses (NAME=<name>). A copy that still says
//      the old episode's name writes the old episode's .mp4 and .srt under the old name, so the film that ships is
//      called after another episode.
//   2. The files a person writes by hand and that carry the episode's identity — TREATMENT.md, research/FACTS.md,
//      src/film.js, src/timeline.js, index.html, CREDITS — must not be byte-identical to the same file in another film
//      folder of this repository. Identical means "copied and never written"; the shared drawing helpers (src/cel.js,
//      src/character.js) are legitimately identical and are not checked. events.json is generated by core/render/events.mjs
//      and is not checked either.
// Every line in voice/lines.json must appear in the timeline's SEQ, and every SEQ entry must be a line. A line
// with no place in the timeline never gets a subtitle and never gets a duration.
//
// When two folders hold the same file, the newer one is the copy: the older file is where the content came from.
//
// The other films of the library come from core/render/films.mjs, the one module that knows where the films are:
// the sibling set spans films/ and channels/*/*, so an episode is compared with the one-shots and with the other
// episodes of its channel.
//
// Exit code: 0 nothing found; 1 problems found; 2 usage.
import fs from 'fs';
import path from 'path';
import { REPO_ROOT, listFilms } from './films.mjs';

const args = process.argv.slice(2);
if (!args.length) { console.error('usage: node core/render/filmcheck.mjs <film-folder> [<film-folder> ...]'); process.exit(2); }

const IDENTITY_FILES = ['TREATMENT.md', 'CREDITS', 'index.html', 'research/FACTS.md', 'src/film.js', 'src/timeline.js'];
const read = f => { try { return fs.readFileSync(f, 'utf8'); } catch { return null; } };
const mtime = f => { try { return fs.statSync(f).mtimeMs; } catch { return 0; } };

// the name the finished movie is written under: the mux line's output, with $NAME resolved
function outputNames(build) {
  const names = new Set();
  const nm = /^NAME=(.+)$/m.exec(build);
  const name = nm ? nm[1].trim() : null;
  const text = name ? build.replaceAll('$NAME', name) : build;
  const mux = /mux\.sh[^\n]*/.exec(text);
  if (mux) {
    const args = [...mux[0].matchAll(/"\$OUT\/([A-Za-z0-9_.-]+)\.mp4"/g)].map(m => m[1]);
    const last = args[args.length - 1];   // the first is the video-only intermediate
    if (last) names.add(last);
  }
  if (name) names.add(name);
  return [...names];
}

// every film folder of the library, so the copy can be compared with its source. The list comes from the discovery
// module: films/ and channels/*/*, at any depth.
const siblings = listFilms().map(f => ({ name: f.rel, dir: f.dir }));

// the folder a check names: the path it was given, relative to the repository when it is inside it
function label(dir) {
  const rel = path.relative(REPO_ROOT, dir);
  return rel && !rel.startsWith('..') ? rel : dir;
}

let bad = 0;
const fail = (folder, msg) => { console.log(`BAD ${folder}: ${msg}`); bad++; };
const ok = (folder, msg) => console.log(`OK  ${folder}: ${msg}`);

for (const arg of args) {
  const folder = path.isAbsolute(arg) ? path.resolve(arg) : (fs.existsSync(arg) ? path.resolve(arg) : path.resolve(REPO_ROOT, arg));
  const name = label(folder);
  console.log(`--- ${folder}`);

  // 1. the name build.sh writes under is this film's own
  const build = read(path.join(folder, 'build.sh'));
  if (build === null) fail(name, 'no build.sh: the film cannot be rebuilt');
  else {
    const mine = outputNames(build);
    if (!mine.length) fail(name, 'build.sh writes no .mp4 — it cannot name its outputs');
    else {
      const clash = [];
      for (const s of siblings) {
        if (s.dir === folder) continue;
        const theirs = outputNames(read(path.join(s.dir, 'build.sh')) || '');
        for (const n of mine) if (theirs.includes(n)) clash.push(`${n} (${s.name})`);
      }
      if (clash.length) fail(name, `build.sh writes ${clash.join(', ')} — another film already ships under that name`);
      else ok(name, `build.sh writes ${mine.join(', ')}`);
    }
  }

  // 2. the identity files are this episode's own
  let copied = 0;
  const labels = [];
  for (const rel of IDENTITY_FILES) {
    const mine = read(path.join(folder, rel));
    if (mine === null) continue;
    // the episode number the file's heading claims ("Tập 02", "tập 2")
    const head = mine.split('\n').slice(0, 5).join('\n');
    const lab = /tập\s*0?(\d+)/i.exec(head);
    if (lab) labels.push({ rel, label: lab[1] });
    for (const s of siblings) {
      if (s.dir === folder) continue;
      const theirs = read(path.join(s.dir, rel));
      if (theirs === null || theirs !== mine) continue;
      // the older file is the source, the newer one is the copy that was never written
      const isCopy = mtime(path.join(folder, rel)) >= mtime(path.join(s.dir, rel));
      if (isCopy) { fail(name, `${rel} is byte-identical to ${s.name} — copied and never written`); copied++; }
    }
  }
  if (!copied) ok(name, 'the treatment, the research, the shots and the title are this episode\'s own');

  // 2b. every file that names an episode names the same one
  const distinct = [...new Set(labels.map(l => l.label))];
  if (distinct.length > 1) {
    for (const l of labels) {
      if (l.label !== distinct[0]) fail(name, `${l.rel} says "tập ${l.label}" but the other files say "tập ${distinct[0]}"`);
    }
  } else if (labels.length) ok(name, `every file that names an episode says tập ${distinct[0]}`);

  // 3. the voice and the timeline agree
  const linesPath = path.join(folder, 'voice/lines.json');
  const timelinePath = path.join(folder, 'src/timeline.js');
  const linesRaw = read(linesPath), timeline = read(timelinePath);
  if (linesRaw === null || timeline === null) {
    ok(name, 'the voice or the timeline is not written yet — nothing to compare');
  } else {
    let ids = [];
    try {
      const parsed = JSON.parse(linesRaw);
      ids = (Array.isArray(parsed) ? parsed : []).map(l => String(l.id));
    } catch { fail(name, 'voice/lines.json is not valid JSON'); }
    // only the SEQ array: the subtitle chunks below it carry words, not line ids
    const seqBlock = /export\s+const\s+SEQ\s*=\s*\[([\s\S]*?)\n\];/.exec(timeline);
    const seq = seqBlock ? [...seqBlock[1].matchAll(/\[\s*'([A-Za-z0-9_-]+)'/g)].map(m => m[1]) : [];
    if (!seq.length) fail(name, 'src/timeline.js has no SEQ entries — nothing gets a duration');
    const missing = ids.filter(i => !seq.includes(i));
    const extra = seq.filter(i => !ids.includes(i));
    if (missing.length) fail(name, `${missing.length} line(s) have no place in the timeline: ${missing.slice(0, 6).join(', ')}`);
    if (extra.length) fail(name, `${extra.length} timeline entry(ies) have no line: ${extra.slice(0, 6).join(', ')}`);
    if (!missing.length && !extra.length && ids.length) ok(name, `${ids.length} lines and ${seq.length} timeline entries match`);
  }

  // 4. sound events and voice check (prevents silent films with empty window.EV)
  const eventsPath = path.join(folder, 'events.json');
  const eventsRaw = read(eventsPath);
  if (eventsRaw !== null) {
    try {
      const evData = JSON.parse(eventsRaw);
      const evList = Array.isArray(evData.ev) ? evData.ev : [];
      const voiceEvs = evList.filter(e => e.type === 'voice');
      if (voiceEvs.length === 0) {
        fail(name, 'events.json has 0 voice events — window.EV in src/film.js was left empty; the audio will have no speech!');
      }
    } catch {}
  }

  // 5. anti-robotic conversational script check (prevents slide-deck bullet scripts)
  if (linesRaw !== null) {
    try {
      const parsed = JSON.parse(linesRaw);
      const roboticLines = (Array.isArray(parsed) ? parsed : []).filter(l => /^(?:Một|Hai|Ba|Bốn|Năm|Sáu|Bảy|Tám|Chín|Mười|\d+)\s*[—–-]/i.test(l.text || ''));
      if (roboticLines.length > 2) {
        fail(name, `voice/lines.json has ${roboticLines.length} robotic numbered lines ("Một —", "Hai —"). Scripts must be conversational storytelling, not slide decks!`);
      }
    } catch {}
  }
}

if (bad) { console.log(`filmcheck: FAILED (${bad} problem${bad > 1 ? 's' : ''})`); process.exit(1); }
console.log('filmcheck: PASS');
