"""Generate FILMS.md from the films' manifests: python3 tools/gen_films_index.py

The index of the library is generated, never written by hand: this script reads every film's own manifest
(film.json) and writes FILMS.md — the table of the films and the section of the channels.

The films come from core/render/films.mjs, the one module that knows where the films are; this script asks it for the
list and reads the manifests it names. There is one implementation of the layout, in node.

**A film in preparation is not in the index.** A film whose movie is not built yet says nothing yet, so it has no
row; the check that reads this file knows that and does not ask for one. A film whose movie is there but whose
manifest is missing or names another movie cannot be indexed either: the script says so and exits non-zero, because an
index that silently leaves a film out is worse than no index.

Exit code: 0 the index is complete; 1 a film cannot be indexed, or the discovery module could not be run.
"""
import json
import os
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
INDEX = os.path.join(ROOT, 'FILMS.md')
DISCOVERY = os.path.join(ROOT, 'core', 'render', 'films.mjs')
UNKNOWN = '—'          # what a cell says when the manifest does not know yet


def discovery():
    """What core/render/films.mjs knows: the channels and the films of the library."""
    try:
        out = subprocess.run(['node', DISCOVERY, '--json'], capture_output=True, text=True, cwd=ROOT, timeout=120)
    except (OSError, subprocess.SubprocessError) as e:
        sys.exit(f'gen_films_index: the discovery module could not be run ({e}): node is needed to know where the films are')
    if out.returncode != 0:
        sys.exit(f'gen_films_index: the discovery module failed: {out.stderr.strip() or out.stdout.strip()}')
    try:
        return json.loads(out.stdout)
    except ValueError as e:
        sys.exit(f'gen_films_index: the discovery module printed something that is not JSON: {e}')


def movies_in(folder):
    """the movies in a film's own folder"""
    try:
        return sorted(f for f in os.listdir(folder) if f.endswith('.mp4'))
    except OSError:
        return []


def film_state(film):
    """How the film stands, and why: (status, name, path).

      'built'     the manifest names a movie and the file is there
      'preparing' the film has no movie yet: it is in preparation
      'wrong'     the film has a movie, but the manifest names another one
      'unwritten' the film has a movie and no manifest at all
    """
    folder = os.path.join(ROOT, film['rel'])
    manifest = film['manifest'] or {}
    named = (manifest.get('movie') or '').strip()
    there = movies_in(folder)
    if named:
        path = os.path.join(folder, named)
        if os.path.isfile(path):
            return 'built', named, path
        if there:
            return 'wrong', named, path
        return 'preparing', named, path
    if there:
        return 'unwritten', there[0], os.path.join(folder, there[0])
    return 'preparing', '', None


def film_row(film):
    """The table row of one film, read from its manifest."""
    manifest = film['manifest'] or {}
    title = (manifest.get('title') or '').strip()
    movie = (manifest.get('movie') or '').strip()
    runtime = (manifest.get('runtime') or '').strip()
    folder = film['rel'] + '/'
    return '| {} | `{}` | {} | `{}` |'.format(
        title or UNKNOWN,
        folder,
        runtime or UNKNOWN,
        (film['rel'] + '/' + movie) if movie else UNKNOWN,
    )


def channel_row(channel):
    """The table row of one channel: it names the channel's own map."""
    folder = channel['rel'] + '/'
    return '| {} | `{}` | [`CHANNEL.md`]({}) |'.format(channel['name'] or channel['slug'], folder, folder + 'CHANNEL.md')


def render(lib):
    """The whole file: the table of the films, then the section of the channels.

    The films that are in preparation have no row: they say nothing yet."""
    films = lib['films']
    channels = lib['channels']
    rows = []
    problems = []
    for film in films:
        rel = film['rel']
        status, name, path = film_state(film)
        if status == 'built':
            rows.append(film_row(film))
        elif status == 'preparing':
            print(f'  in preparation: {rel} (no movie yet)')
        elif status == 'wrong':
            there = movies_in(os.path.join(ROOT, rel))
            print(f'  the manifest of {rel} names {name}, and the movie that is there is {there[0]}')
            problems.append(rel)
        else:   # unwritten
            print(f'  {rel} has a movie ({name}) but no manifest (film.json): it cannot be indexed')
            problems.append(rel)
    out = []
    out.append('# Films')
    out.append('')
    out.append('Generated by `tools/gen_films_index.py` from the films\' own manifests — **do not edit this file by '
               'hand**: run the script instead.')
    out.append('')
    out.append('Every film of the library, one row each. The one-shots live in `films/`; the episodes live under the '
               'channel they belong to. A film that is still in preparation has no row: it says nothing yet.')
    out.append('')
    out.append('| Film | Folder | Runtime | Movie |')
    out.append('|---|---|---|---|')
    out.extend(rows)
    out.append('')
    out.append('## Channels')
    out.append('')
    if channels:
        out.append('| Channel | Folder | Map |')
        out.append('|---|---|---|')
        for channel in channels:
            out.append(channel_row(channel))
    else:
        out.append('No channel yet: a channel is a folder under `channels/` that holds a `CHANNEL.md`.')
    out.append('')
    return '\n'.join(out), problems


def main():
    lib = discovery()
    films = lib['films']
    if not films:
        sys.exit('gen_films_index: no film was found: the discovery module found nothing, so the index would be empty')
    text, problems = render(lib)
    with open(INDEX, 'w', encoding='utf8') as fh:
        fh.write(text)
    print(f'gen_films_index: wrote {os.path.relpath(INDEX, ROOT)} ({len(films)} film(s), {len(lib["channels"])} channel(s))')
    if problems:
        sys.exit(f'gen_films_index: the index is incomplete: {len(problems)} film(s) cannot be indexed')
    return 0


if __name__ == '__main__':
    sys.exit(main())
