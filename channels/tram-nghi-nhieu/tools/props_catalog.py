#!/usr/bin/env python3
"""The props catalogue of an episode, whichever way it keeps its props — python3 props_catalog.py <episode>

Two layouts, one module that knows both:

  split   src/props/<id>.js   one prop per file: its builders, and exactly one
                              `export const PROP = { name: '<tên vật như lời gọi>', view: () => <Object3D> };`
          src/props/_*.js     helpers shared by several props (no PROP); a change there is a change to
                              every prop file that imports it
          src/props.js        a GENERATED barrel (`--write-index`): `export * from` every file, and
                              `export const PROPS = {name: view, …}`. Never edited by hand.
  legacy  src/props.js        every prop in one file, with `export const PROPS = { 'tên vật': () => …, }`

Python use:  import props_catalog as pc
  pc.catalog(ep)          -> [{id, name, file, layout}] in PROPS order; [] when the episode has no props file
  pc.digest(ep, item)     -> sha256 hex of the source of that prop (split: its file + the `_` files it imports,
                             transitively; legacy: the whole src/props.js)
  pc.write_index(ep)      -> writes the barrel (split layout); returns its path
  pc.problems(ep)         -> [str]; split layout only; [] = fine
  pc.layout(ep)           -> 'split' | 'legacy' | None
  pc.view_source(ep, item)-> the text of the prop's `view` (what the catalogue calls) — used by check_props_used
  pc.strip_catalogue(ep)  -> the episode's src text with every catalogue entry cut out (what the film itself calls)

CLI:  props_catalog.py <ep>               id | name | file | digest[:12]
      props_catalog.py <ep> --write-index
      props_catalog.py <ep> --check       prints problems, exit 1 if any
      props_catalog.py --selftest

The legacy slug is the name without accents (đ -> d), lower case, runs of other characters -> '-',
cut at 48 characters on a word edge; a second prop with the same slug gets '-2', '-3'. It is a function of
the name alone, so it is stable while the name is.
The order of the split catalogue is the order of the barrel already on disk (files that are gone drop out,
new files are appended, sorted by id), so adding a prop never renumbers the others (p_NN.jpg, "#25").
"""
import hashlib
import os
import re
import sys
import unicodedata

HEADER = ("// GENERATED by tools/props_catalog.py --write-index — do not edit by hand.\n"
          "// One prop per file in src/props/; add or remove a file, then run the command again.\n")
IMPORT_RE = re.compile(r"""(?:from|import)\s*['"]\./(_[\w.-]+?\.js)['"]""")
EXPORT_RE = re.compile(r"^export\s+(?:async\s+)?(?:function\*?|const|let|var|class)\s+([A-Za-z_$][\w$]*)", re.M)
EXPORT_LIST_RE = re.compile(r"^export\s*\{([^}]*)\}", re.M)
BARREL_IMPORT_RE = re.compile(r"^import \{ PROP as _p_\d+ \} from '\./props/([^']+)\.js';", re.M)
SLUG_MAX = 48


def _read(p):
    with open(p, encoding='utf-8') as fh:
        return fh.read()


def slug(name):
    s = unicodedata.normalize('NFD', name.lower().replace('đ', 'd'))
    s = ''.join(c for c in s if not unicodedata.combining(c))
    s = re.sub(r'[^a-z0-9]+', '-', s).strip('-')
    if len(s) > SLUG_MAX:
        cut = s[:SLUG_MAX]
        s = cut.rsplit('-', 1)[0] if '-' in cut and s[SLUG_MAX] != '-' else cut
    return s or 'vat'


def _pdir(ep):
    return os.path.join(ep, 'src', 'props')


def _barrel(ep):
    return os.path.join(ep, 'src', 'props.js')


def _split_files(ep):
    d = _pdir(ep)
    if not os.path.isdir(d):
        return [], []
    fs = sorted(f for f in os.listdir(d) if f.endswith('.js'))
    return [f[:-3] for f in fs if not f.startswith('_')], [f[:-3] for f in fs if f.startswith('_')]


def layout(ep):
    props, _ = _split_files(ep)
    if props:
        return 'split'
    if os.path.isfile(_barrel(ep)):
        return 'legacy'
    return None


def _block(text, start):
    """text from `start` to the end of the first {...} literal after it, strings and // comments skipped"""
    i = text.find('{', start)
    if i < 0:
        return None
    depth, q, j = 0, None, i
    while j < len(text):
        c = text[j]
        if q:
            if c == '\\':
                j += 1
            elif c == q:
                q = None
        elif c in '\'"`':
            q = c
        elif c == '/' and text[j:j + 2] == '//':
            j = text.find('\n', j)
            if j < 0:
                return None
            continue
        elif c == '{':
            depth += 1
        elif c == '}':
            depth -= 1
            if depth == 0:
                return text[start:j + 1]
        j += 1
    return None


def _prop_block(text):
    m = re.search(r'^export\s+const\s+PROP\s*=', text, re.M)
    if not m:
        return None
    return _block(text, m.start())


def _prop_name(text):
    b = _prop_block(text)
    if not b:
        return None
    m = re.search(r"""\bname\s*:\s*(['"`])((?:\\.|(?!\1).)*)\1""", b)
    return m.group(2).replace("\\'", "'").replace('\\"', '"') if m else None


def _legacy_entries(ep):
    """[(name, entry_text)] of the legacy PROPS object"""
    p = _barrel(ep)
    if not os.path.isfile(p):
        return []
    text = _read(p)
    i = text.find('export const PROPS')
    if i < 0:
        return []
    end = text.find('\n};', i)
    body = text[i:end] if end >= 0 else text[i:]
    pat = re.compile(r"^\s*(['\"])((?:\\.|(?!\1).)+)\1\s*:\s*", re.M)
    ms = list(pat.finditer(body))
    out = []
    for k, m in enumerate(ms):
        out.append((m.group(2).replace("\\'", "'"), body[m.end():ms[k + 1].start() if k + 1 < len(ms) else len(body)]))
    return out


def _barrel_order(ep):
    p = _barrel(ep)
    return BARREL_IMPORT_RE.findall(_read(p)) if os.path.isfile(p) else []


def _split_order(ep):
    props, _ = _split_files(ep)
    have = set(props)
    order = [i for i in _barrel_order(ep) if i in have]
    return order + [i for i in sorted(props) if i not in order]


def catalog(ep):
    lay = layout(ep)
    if lay == 'legacy':
        out, seen = [], {}
        for name, _ in _legacy_entries(ep):
            s = slug(name)
            seen[s] = seen.get(s, 0) + 1
            out.append({'id': s if seen[s] == 1 else '%s-%d' % (s, seen[s]), 'name': name,
                        'file': 'src/props.js', 'layout': 'legacy'})
        return out
    if lay == 'split':
        out = []
        for i in _split_order(ep):
            name = _prop_name(_read(os.path.join(_pdir(ep), i + '.js')))
            if name is not None:
                out.append({'id': i, 'name': name, 'file': 'src/props/%s.js' % i, 'layout': 'split'})
        return out
    return []


def _closure(ep, fname):
    """fname plus the `_` files it imports, transitively — in a stable order"""
    seen, todo = [], [fname]
    while todo:
        f = todo.pop()
        if f in seen:
            continue
        p = os.path.join(_pdir(ep), f)
        if not os.path.isfile(p):
            continue
        seen.append(f)
        todo += [g for g in IMPORT_RE.findall(_read(p)) if g.startswith('_')]
    return [fname] + sorted(f for f in seen if f != fname)


def digest(ep, item):
    h = hashlib.sha256()
    if item['layout'] == 'legacy':
        h.update(open(_barrel(ep), 'rb').read())
    else:
        for f in _closure(ep, os.path.basename(item['file'])):
            h.update(f.encode() + b'\0' + open(os.path.join(_pdir(ep), f), 'rb').read() + b'\0')
    return h.hexdigest()


def view_source(ep, item):
    if item['layout'] == 'legacy':
        for name, entry in _legacy_entries(ep):
            if name == item['name']:
                return entry
        return ''
    block = _prop_block(_read(os.path.join(ep, item['file']))) or ''
    m = re.search(r'\bview\s*:', block)
    return block[m.end():] if m else block


def strip_catalogue(ep):
    """every .js of src/ (and src/props/) as one text, the catalogue entries cut out: what the film itself calls"""
    src = os.path.join(ep, 'src')
    parts = []
    for d in (src, _pdir(ep)):
        if not os.path.isdir(d):
            continue
        for f in sorted(os.listdir(d)):
            p = os.path.join(d, f)
            if not (f.endswith('.js') and os.path.isfile(p)):
                continue
            t = _read(p)
            if d == src and f == 'props.js':
                if layout(ep) == 'split':
                    continue            # the generated barrel calls nothing
                i = t.find('export const PROPS')
                if i >= 0:
                    e = t.find('\n};', i)
                    t = t[:i] + (t[e:] if e >= 0 else '')
            else:
                b = _prop_block(t)
                if b:
                    t = t.replace(b, '')
            parts.append(t)
    return '\n'.join(parts)


def _exports(text):
    names = set(EXPORT_RE.findall(text))
    for lst in EXPORT_LIST_RE.findall(text):
        for part in lst.split(','):
            part = part.strip()
            if part:
                names.add(part.split(' as ')[-1].strip())
    names.discard('PROP')
    return names


def render_index(ep):
    order = _split_order(ep)
    _, helpers = _split_files(ep)
    lines = [HEADER]
    for i in helpers + order:
        lines.append("export * from './props/%s.js';" % i)
    lines.append('')
    for n, i in enumerate(order, 1):
        lines.append("import { PROP as _p_%d } from './props/%s.js';" % (n, i))
    lines.append('export const PROPS = Object.fromEntries([%s].map(p => [p.name, p.view]));'
                 % ', '.join('_p_%d' % n for n in range(1, len(order) + 1)))
    return '\n'.join(lines) + '\n'


def write_index(ep):
    p = _barrel(ep)
    if not _split_files(ep)[0]:
        raise ValueError('props_catalog: %s has no src/props/<id>.js — nothing to index' % ep)
    text = render_index(ep)        # before opening for writing: it reads the old barrel for the order
    with open(p, 'w', encoding='utf-8') as fh:
        fh.write(text)
    return p


def problems(ep):
    if layout(ep) != 'split':
        return []
    out = []
    props, helpers = _split_files(ep)
    names = {}
    exported = {}
    for i in props + helpers:
        text = _read(os.path.join(_pdir(ep), i + '.js'))
        if i in props:
            if not re.search(r'^export\s+const\s+PROP\s*=', text, re.M):
                out.append('src/props/%s.js: không có `export const PROP = { name, view }`' % i)
            else:
                n = _prop_name(text)
                if n is None:
                    out.append("src/props/%s.js: PROP không có `name: '…'` đọc được" % i)
                else:
                    names.setdefault(n, []).append(i)
                if not re.search(r'\bview\s*:|\bview\s*\(', _prop_block(text) or ''):
                    out.append('src/props/%s.js: PROP không có `view`' % i)
        elif re.search(r'^export\s+const\s+PROP\b', text, re.M):
            out.append('src/props/%s.js: tệp dùng chung (_) không được có PROP' % i)
        for e in _exports(text):
            exported.setdefault(e, []).append(i)
    for n, fs in names.items():
        if len(fs) > 1:
            out.append('tên vật "%s" trùng ở %s' % (n, ', '.join('src/props/%s.js' % f for f in fs)))
    for e, fs in exported.items():
        if len(fs) > 1:
            out.append('export `%s` có ở nhiều tệp (%s): `export *` trong src/props.js sẽ bỏ nó đi âm thầm'
                       % (e, ', '.join(fs)))
    # Một tệp dùng chung (`_`) mà tệp vật import mà KHÔNG TỒN TẠI: `_closure` bỏ qua nó âm thầm, nên
    # digest của vật băm thiếu mà không báo — phán quyết của vật không đổi dù mã đã đổi. Đây là
    # loại lỗi im lặng, nên nó phải được nói ra (M28).
    for i in props + helpers:
        text = _read(os.path.join(_pdir(ep), i + '.js'))
        for g in IMPORT_RE.findall(text):
            if not os.path.isfile(os.path.join(_pdir(ep), g)):
                out.append('src/props/%s.js import "./%s" mà tệp đó không có — digest của vật sẽ băm '
                           'thiếu mà không báo' % (i, g))
    p = _barrel(ep)
    if not os.path.isfile(p):
        out.append('src/props.js chưa có — chạy props_catalog.py --write-index')
    elif _read(p) != render_index(ep):
        have, want = set(_barrel_order(ep)), set(props)
        why = []
        if want - have:
            why.append('thiếu ' + ', '.join(sorted(want - have)))
        if have - want:
            why.append('thừa ' + ', '.join(sorted(have - want)))
        if not _read(p).startswith(HEADER):
            why.append('mất dòng đầu "GENERATED" (sửa tay?)')
        out.append('src/props.js không khớp các tệp trong src/props/ (%s) — nó do máy sinh, không sửa tay: '
                   'chạy props_catalog.py --write-index' % ('; '.join(why) or 'nội dung khác bản máy sinh — sửa tay?'))
    return out


def main(argv):
    if '--selftest' in argv:
        return selftest()
    args = [a for a in argv if not a.startswith('--')]
    if not args:
        print(__doc__)
        return 2
    ep = args[0]
    if '--write-index' in argv:
        try:
            print(write_index(ep))
        except ValueError as e:
            print(e)
            return 2
        return 0
    if '--check' in argv:
        ps = problems(ep)
        for p in ps:
            print(p)
        if not ps:
            print('props_catalog: ổn (%s, %d vật)' % (layout(ep) or 'không có vật', len(catalog(ep))))
        return 1 if ps else 0
    for it in catalog(ep):
        print('%s | %s | %s | %s' % (it['id'], it['name'], it['file'], digest(ep, it)[:12]))
    return 0


def selftest():
    import shutil
    import tempfile
    fails = []

    def case(name, ok, detail=''):
        print('%-4s %s' % ('ok' if ok else 'FAIL', name))
        if not ok:
            fails.append(name + (' — ' + str(detail) if detail else ''))

    root = tempfile.mkdtemp(prefix='props-catalog-')

    def w(ep, rel, text):
        p = os.path.join(ep, rel)
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, 'w', encoding='utf-8') as fh:
            fh.write(text)
    try:
        # ── legacy
        lg = os.path.join(root, 'lg')
        w(lg, 'src/props.js',
          "import * as THREE from 'three';\nexport function a() { return {}; }\n"
          "export const PROPS = {\n  'Bàn tay người': () => a().group,\n"
          "  // chú thích 'x': y\n  'Bàn tay người!': () => b().group,\n  'đèn': () => c(),\n};\n")
        c = catalog(lg)
        case('legacy: tên theo thứ tự', [x['name'] for x in c] == ['Bàn tay người', 'Bàn tay người!', 'đèn'], c)
        case('legacy: slug ascii, duy nhất', [x['id'] for x in c] == ['ban-tay-nguoi', 'ban-tay-nguoi-2', 'den'], c)
        case('legacy: file và layout', c[0]['file'] == 'src/props.js' and c[0]['layout'] == 'legacy')
        case('legacy: digest là của cả tệp', digest(lg, c[0]) == digest(lg, c[2]))
        case('legacy: không có problems', problems(lg) == [])
        case('legacy: view_source', 'b()' in view_source(lg, c[1]), view_source(lg, c[1]))
        long = slug('bàn phơi gỗ có nan, trải quần áo ra để so sánh')
        case('slug dài cắt ở ranh giới từ', long == 'ban-phoi-go-co-nan-trai-quan-ao-ra-de-so-sanh', long)
        case('không có tệp props thì []', catalog(os.path.join(root, 'none')) == [])
        # ── split
        sp = os.path.join(root, 'sp')
        w(sp, 'src/props/_shared.js', "export const M = {};\nexport function rbox() {}\n")
        w(sp, 'src/props/_deep.js', "export const D = 1;\n")
        w(sp, 'src/props/gian-phoi.js',
          "import { M } from './_shared.js';\nexport function gian() { return { group: M }; }\n"
          "export const PROP = { name: 'giàn phơi {x}', view: () => gian().group };\n")
        w(sp, 'src/props/kep.js',
          "import { rbox } from './_shared.js';\nexport function kep() { return {group: rbox}; }\n"
          "export const PROP = {\n  name: \"kẹp gỗ\",\n  view: () => kep().group,\n};\n")
        w(sp, 'src/props/ao.js', "export function ao() { return {group: 1}; }\nexport const PROP = { name: 'áo', view: () => ao().group };\n")
        write_index(sp)
        c = catalog(sp)
        case('split: thứ tự = thứ tự máy sinh (sắp theo id lần đầu)', [x['id'] for x in c] == ['ao', 'gian-phoi', 'kep'], c)
        case('split: tên đọc từ PROP', [x['name'] for x in c] == ['áo', 'giàn phơi {x}', 'kẹp gỗ'], c)
        case('split: sau khi sinh thì sạch', problems(sp) == [], problems(sp))
        idx = _read(_barrel(sp))
        case('barrel có đủ dòng', "export * from './props/_shared.js';" in idx and 'Object.fromEntries' in idx
             and idx.startswith('// GENERATED'), idx)
        d0 = {x['id']: digest(sp, x) for x in c}
        w(sp, 'src/props/_shared.js', "export const M = {a: 1};\nexport function rbox() {}\n")
        d1 = {x['id']: digest(sp, x) for x in c}
        case('đổi _shared đổi digest của tệp import nó, không đổi tệp khác',
             d0['gian-phoi'] != d1['gian-phoi'] and d0['kep'] != d1['kep'] and d0['ao'] == d1['ao'])
        w(sp, 'src/props/gian-phoi.js', _read(os.path.join(sp, 'src/props/gian-phoi.js'))
          .replace("'./_shared.js'", "'./_deep.js'").replace('{ M }', '{ D as M }'))
        w(sp, 'src/props/_deep.js', "import { M } from './_shared.js';\nexport const D = M;\n")
        a = digest(sp, catalog(sp)[1])
        w(sp, 'src/props/_shared.js', "export const M = {a: 2};\nexport function rbox() {}\n")
        case('digest theo _ bắc cầu', a != digest(sp, catalog(sp)[1]))
        # M28: một tệp dùng chung (`_`) mà tệp vật import mà không tồn tại — `_closure` bỏ qua nó
        # âm thầm, nên digest băm thiếu mà không báo. Đó là loại lỗi im lặng: phải nói ra.
        w(sp, 'src/props/kep.js',
          "import { rbox } from './_khong-co.js';\nexport function kep() { return {group: rbox}; }\n"
          "export const PROP = {\n  name: \"kẹp gỗ\",\n  view: () => kep().group,\n};\n")
        ps = problems(sp)
        case('tệp dùng chung không tồn tại thì báo',
             any('_khong-co.js' in x and 'không có' in x for x in ps), ps)
        # trả lại tệp vật về hình dạng lành lặn, để các ca sau đo trên một tập sạch
        w(sp, 'src/props/kep.js',
          "import { rbox } from './_shared.js';\nexport function kep() { return {group: rbox}; }\n"
          "export const PROP = {\n  name: \"kẹp gỗ\",\n  view: () => kep().group,\n};\n")
        # a new file is appended, not sorted in
        w(sp, 'src/props/aa-moi.js', "export const PROP = { name: 'mới', view: () => ({}) };\n")
        case('thêm tệp mà chưa sinh lại thì báo', any('thiếu aa-moi' in p for p in problems(sp)), problems(sp))
        write_index(sp)
        case('vật mới nằm cuối, số cũ giữ nguyên',
             [x['id'] for x in catalog(sp)] == ['ao', 'gian-phoi', 'kep', 'aa-moi'], catalog(sp))
        # problems
        w(sp, 'src/props/thieu.js', "export function t() {}\n")
        case('tệp vật thiếu PROP thì báo', any('thieu.js' in p and 'PROP' in p for p in problems(sp)), problems(sp))
        os.remove(os.path.join(sp, 'src/props/thieu.js'))
        w(sp, 'src/props/trung.js', "export const PROP = { name: 'áo', view: () => ({}) };\n")
        write_index(sp)
        case('tên trùng thì báo', any('trùng' in p for p in problems(sp)), problems(sp))
        os.remove(os.path.join(sp, 'src/props/trung.js'))
        write_index(sp)
        ao = os.path.join(sp, 'src/props/ao.js')
        good = _read(ao)
        w(sp, 'src/props/ao.js', good + "export function rbox() {}\n")
        case('export trùng giữa các tệp thì báo', any('rbox' in p for p in problems(sp)), problems(sp))
        w(sp, 'src/props/ao.js', good)
        w(sp, 'src/props.js', _read(_barrel(sp)) + '\nexport const X = 1;\n')
        case('sửa tay barrel thì báo', any('sửa tay' in p for p in problems(sp)), problems(sp))
        write_index(sp)
        case('sinh lại thì sạch', problems(sp) == [], problems(sp))
        c = catalog(sp)
        case('split: view_source là khối PROP', 'ao()' in view_source(sp, c[0]) and 'name' not in view_source(sp, c[0]), view_source(sp, c[0]))
        case('strip_catalogue bỏ khối PROP', 'view:' not in strip_catalogue(sp))
    finally:
        shutil.rmtree(root, ignore_errors=True)
    for f in fails:
        print('FAIL ' + f)
    print('props_catalog --selftest: %s' % ('%d FAIL' % len(fails) if fails else 'ok'))
    return 1 if fails else 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
