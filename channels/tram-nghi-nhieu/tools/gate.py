"""The review gate of an episode: the voice and the render run only on what the independent critic passed.

  python3 gate.py status <episode>                      every step: items passed, open, to fix, not judged yet
  python3 gate.py check <episode> [--for voice|render]  exit 1 with the reason when that step may not run
      voice   outline and script are closed (tts_vi.py asks)
      render  outline, script, look, props and picture are closed (mix.py and core/render/video.mjs ask)
  python3 gate.py --selftest

The state of a step lives in <episode>/review/<step>.json and only review.py writes it. A step is judged item by
item (the one outline, each spoken line, each hero still, each prop, each line's picture). Every item is
  PASS  every CHẶN criterion of the step's rubric was ĐẠT,
  FAIL  a CHẶN criterion was LỖI: fix it and run review again,
  OPEN  it failed three times: the step goes on, and the item stays listed in the reports.
A step is closed when every item it has now is PASS or OPEN and nothing judged has changed since:
  outline, look   plans: once closed they stay closed (later edits are expected)
  script          each line's text is what was judged
  props           each prop's source (props_catalog.digest) is what was judged
  picture         each line's text, and the film's code (src/, index.html) is what the last picture round saw
The gate catches mistakes, not forgery: a state file written by hand is not a review.
"""
import glob, hashlib, json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

STEPS = ('outline', 'script', 'look', 'props', 'picture', 'final')
PREV = {'script': 'outline', 'look': 'script', 'props': 'look', 'picture': 'props', 'final': 'picture'}
NEEDS = {'voice': ('outline', 'script'), 'render': ('outline', 'script', 'look', 'props', 'picture')}
PLANS = ('outline', 'look')
WHAT = {'outline': 'dàn ý', 'script': 'lời kể', 'look': 'khung hình chính', 'props': 'vật dựng',
        'picture': 'hình từng câu', 'final': 'nghiệm thu'}
CLOSED = ('PASS', 'OPEN')
PLACEHOLDER = re.compile(r'placeholder|giữ chỗ', re.I)
NOT_PICTURE = ('timeline.js',)   # regenerated by every build from the voice timings


def sha(b): return hashlib.sha256(b).hexdigest()


def read(p):
    with open(p, 'rb') as f: return f.read()


# ——— what an episode holds now ———

def lines(ep):
    p = os.path.join(ep, 'voice/lines.json')
    return json.load(open(p, encoding='utf-8')) if os.path.isfile(p) else None


def outline_key(ep):
    return sha(b''.join(read(os.path.join(ep, f)) for f in ('TREATMENT.md', 'research/FACTS.md')
                        if os.path.isfile(os.path.join(ep, f))))


def line_keys(ep):
    """{line id: hash of its text}"""
    return {str(x['id']): sha(x['text'].encode()) for x in (lines(ep) or [])}


def hero_files(ep):
    """{stem: path} of the hero stills the look step judges"""
    out = {}
    for p in sorted(glob.glob(os.path.join(ep, 'review/hero/*'))):
        if p.lower().endswith(('.jpg', '.jpeg', '.png')):
            out[os.path.splitext(os.path.basename(p))[0]] = p
    return out


def props_keys(ep):
    """{prop id: {'name', 'src'}}"""
    import props_catalog
    return {x['id']: {'name': x['name'], 'src': props_catalog.digest(ep, x)} for x in props_catalog.catalog(ep)}


def picture_files(ep):
    fs = sorted(glob.glob(os.path.join(ep, 'src/**/*.js'), recursive=True))
    return [f for f in fs if os.path.basename(f) not in NOT_PICTURE] + [os.path.join(ep, 'index.html')]


def picture_src(ep):
    """the film's code as the picture round saw it"""
    h = hashlib.sha256()
    for f in picture_files(ep):
        if os.path.isfile(f): h.update(os.path.relpath(f, ep).encode() + b'\0' + read(f))
    return h.hexdigest()


def placeholders(ep):
    return [os.path.relpath(f, ep) for f in picture_files(ep)
            if f.endswith('.js') and os.path.isfile(f) and PLACEHOLDER.search(open(f, encoding='utf-8').read())]


# ——— the state review.py writes ———

def state_path(ep, step): return os.path.join(ep, 'review', f'{step}.json')


def load(ep, step):
    p = state_path(ep, step)
    if not os.path.isfile(p): return {'step': step, 'round': 0, 'items': {}}
    return json.load(open(p, encoding='utf-8'))


def save(ep, step, st):
    os.makedirs(os.path.join(ep, 'review'), exist_ok=True)
    p = state_path(ep, step)
    tmp = p + '.tmp'
    with open(tmp, 'w', encoding='utf-8') as f: json.dump(st, f, ensure_ascii=False, indent=1)
    os.replace(tmp, p)


def current(ep, step):
    """{item id: key that must match} for the steps whose items the gate can see without rendering"""
    if step == 'outline': return {'dan-y': outline_key(ep)}
    if step in ('script', 'picture'): return line_keys(ep)
    if step == 'look': return {k: None for k in hero_files(ep)}
    if step == 'props': return {k: v['src'] for k, v in props_keys(ep).items()}
    return {}


def tally(ep, step):
    """counts of PASS / OPEN / FAIL / not judged (or changed since) over the items the episode has now"""
    st, now = load(ep, step), current(ep, step)
    c = {'PASS': [], 'OPEN': [], 'FAIL': [], 'chưa chấm': []}
    field = 'src' if step in ('props', 'picture') else 'key'   # picture: 'key' also holds the labels review.py saw
    for k, key in now.items():
        rec = st['items'].get(k)
        if not rec or (key is not None and step not in PLANS and rec.get(field) != key):
            c['chưa chấm'].append(k)
        else:
            c[rec.get('verdict') if rec.get('verdict') in c else 'chưa chấm'].append(k)
    return c


def why_open(ep, step):
    """None when the step is closed, else why not"""
    st = load(ep, step)
    if step in PLANS:
        return None if st.get('closed') else ('chưa chấm' if not st['items'] else 'còn mục phải sửa')
    if step == 'props' and not current(ep, 'props'):
        return 'tập chưa có vật nào (src/props/ hay src/props.js)'
    c = tally(ep, step)
    bad = c['FAIL'] + c['chưa chấm']
    if bad:
        head = ', '.join(bad[:6]) + (f' và {len(bad) - 6} mục khác' if len(bad) > 6 else '')
        return f"{len(c['FAIL'])} mục phải sửa, {len(c['chưa chấm'])} mục chưa chấm hay đã đổi ({head})"
    if step == 'picture' and st.get('src') != picture_src(ep):
        return 'mã của phim đã đổi sau vòng chấm hình cuối (vòng sau chỉ chấm lại những câu có hình đổi)'
    return None


def run_cmd(ep, step):
    return f'sh channels/tram-nghi-nhieu/tools/review.sh {os.path.relpath(ep)} {step}'


def check(ep, step='render'):
    """None when the step may run, else the reason it may not"""
    if not os.path.isdir(ep):
        return f'không có thư mục tập {ep}'
    if not lines(ep):
        # the channel's demo, a rig test: no words, nothing to gate — but only a folder the channel made
        if not any(os.path.exists(os.path.join(ep, f)) for f in ('index.html', 'src', 'film.json')):
            return f'{ep} không phải một tập của kênh (không có voice/lines.json, src/ hay index.html)'
        return None
    for k in NEEDS[step]:
        why = why_open(ep, k)
        if why: return f'{WHAT[k]} ({k}): {why}. Chạy: {run_cmd(ep, k)}'
    if step == 'render':
        ph = placeholders(ep)
        if ph: return f"{', '.join(ph)} vẫn là file giữ chỗ (placeholder): dựng thật rồi chấm lại"
    return None


def status(ep):
    for step in STEPS:
        st = load(ep, step)
        if step == 'final':
            p = os.path.join(ep, 'review/FINAL-QA.md')
            print(f"{step:<8} {'có báo cáo: review/FINAL-QA.md' if os.path.isfile(p) else 'chưa có báo cáo (không chặn)'}")
            continue
        why = why_open(ep, step)
        c = tally(ep, step) if step not in PLANS else None
        counts = (f" — {len(c['PASS'])} ĐẠT, {len(c['OPEN'])} MỞ, {len(c['FAIL'])} phải sửa, {len(c['chưa chấm'])} chưa chấm"
                  if c else '')
        print(f"{step:<8} {'XONG' if why is None else 'CHƯA XONG: ' + why}{counts}")
        opened = [k for k, r in st['items'].items() if r.get('verdict') == 'OPEN']
        if opened: print(f"         mở (đã sai 3 lần, ghi vào báo cáo): {', '.join(opened)}")
    movies = glob.glob(os.path.join(ep, '*.mp4')) + glob.glob(os.path.join(ep, 'out', '*.mp4'))
    print('phim:', ', '.join(os.path.relpath(m, ep) for m in movies) if movies else 'chưa có')
    import layout
    R = layout.report(ep)
    print('bố cục: ' + ('đúng' if not R else 'có thứ nằm sai chỗ (chi tiết: tools/layout.py <tập>)'))
    for r in R: print('  ' + r)


def main(argv=None):
    a = sys.argv[1:] if argv is None else list(argv)
    if a[:1] in (['selftest'], ['--selftest']): return selftest()
    if len(a) < 2: sys.exit(__doc__)
    op, rest = a[0], a[1:]
    step = 'render'
    if '--for' in rest:
        i = rest.index('--for'); step = rest[i + 1] if i + 1 < len(rest) else ''; del rest[i:i + 2]
    if not rest: sys.exit(__doc__)
    ep = os.path.abspath(rest[0])
    if op == 'check':
        if step not in NEEDS: sys.exit(__doc__)
        r = check(ep, step)
        if r: sys.exit('cổng chấm: ' + r)
        print('cổng chấm: PASS')
    elif op == 'status':
        status(ep)
    else:
        sys.exit(__doc__)


def selftest():
    import shutil, tempfile
    tmp = tempfile.mkdtemp(prefix='gate-selftest-')
    ok = True

    def expect(cond, what):
        nonlocal ok
        print(('ok   ' if cond else 'FAIL ') + what)
        ok = ok and cond
    try:
        ep = os.path.join(tmp, 'tap')
        os.makedirs(os.path.join(ep, 'voice')); os.makedirs(os.path.join(ep, 'research')); os.makedirs(os.path.join(ep, 'src'))
        json.dump([{'id': 'c1', 'text': 'một'}, {'id': 'c2', 'text': 'hai'}], open(os.path.join(ep, 'voice/lines.json'), 'w'))
        open(os.path.join(ep, 'TREATMENT.md'), 'w').write('t'); open(os.path.join(ep, 'research/FACTS.md'), 'w').write('f')
        open(os.path.join(ep, 'src/film.js'), 'w').write('// film')
        expect(check(ep, 'voice') is not None, 'a fresh episode may not be voiced')
        save(ep, 'outline', {'step': 'outline', 'round': 1, 'closed': True,
                             'items': {'dan-y': {'key': outline_key(ep), 'verdict': 'PASS'}}})
        keys = line_keys(ep)
        save(ep, 'script', {'step': 'script', 'round': 1,
                            'items': {k: {'key': v, 'verdict': 'PASS'} for k, v in keys.items()}})
        expect(check(ep, 'voice') is None, 'outline + every line PASS → voice may run')
        json.dump([{'id': 'c1', 'text': 'một'}, {'id': 'c2', 'text': 'hai đổi'}], open(os.path.join(ep, 'voice/lines.json'), 'w'))
        r = check(ep, 'voice')
        expect(r is not None and 'c2' in r, 'a changed line reopens the script, naming the line')
        st = load(ep, 'script'); st['items']['c2'] = {'key': line_keys(ep)['c2'], 'verdict': 'OPEN'}; save(ep, 'script', st)
        expect(check(ep, 'voice') is None, 'an OPEN line does not block')
        open(os.path.join(ep, 'TREATMENT.md'), 'w').write('t sửa')
        expect(check(ep, 'voice') is None, 'the outline is a plan: an edit after it closed does not reopen it')
        save(ep, 'look', {'step': 'look', 'round': 1, 'closed': True, 'items': {'h1': {'verdict': 'PASS'}}})
        r = check(ep, 'render')
        expect(r is not None and 'props' in r, 'render needs the props')
        save(ep, 'picture', {'step': 'picture', 'round': 1, 'src': picture_src(ep),
                             'items': {k: {'src': v, 'verdict': 'PASS'} for k, v in line_keys(ep).items()}})
        expect(why_open(ep, 'picture') is None, 'picture closed for the code it saw')
        open(os.path.join(ep, 'src/film.js'), 'w').write('// film sửa')
        expect(why_open(ep, 'picture') is not None, 'a code change reopens the picture')
        open(os.path.join(ep, 'src/timeline.js'), 'w').write('// sinh lại')
        st = load(ep, 'picture'); st['src'] = picture_src(ep); save(ep, 'picture', st)
        open(os.path.join(ep, 'src/timeline.js'), 'w').write('// sinh lại lần nữa')
        expect(why_open(ep, 'picture') is None, 'timeline.js (regenerated each build) does not reopen the picture')
        expect(check(os.path.join(tmp, 'khong-co'), 'render') is not None, 'a missing folder is refused')
        demo = os.path.join(tmp, 'demo'); os.makedirs(os.path.join(demo, 'src'))
        expect(check(demo, 'render') is None, 'the channel demo (no words) passes')
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    print('gate selftest:', 'PASS' if ok else 'FAIL')
    sys.exit(0 if ok else 1)


if __name__ == '__main__':
    main()
